# The distribution grid


def test_the_grid_places_its_boundary_values_where_the_console_does():
    hist = new_histogram()
    cases = {
        QUANTILE_MIN_UA: 0,
        math.nextafter(QUANTILE_MIN_UA, math.inf): 1,
        2.0: 1 + math.floor(math.log10(2.0 / QUANTILE_MIN_UA) * HIST_PER_DECADE),
        0.0: 0,
        -1.0: 0,
        1e9: HIST_BINS,
    }
    for value, expected_bin in cases.items():
        before = hist[expected_bin]
        hist_add(hist, value)
        assert hist[expected_bin] == before + 1, value


def test_nan_lands_in_the_underflow_bin():
    """`not (ua > FLOOR)` is NaN-true in both languages; `ua <= FLOOR` is not.
    Spelled the other way the two grids would disagree on the value a device
    with missing calibration constants produces most."""
    hist = new_histogram()
    hist_add(hist, math.nan)
    assert hist[0] == 1


def test_the_top_bin_is_also_the_overflow_bin():
    hist = new_histogram()
    hist_add(hist, 1e6)
    hist_add(hist, 1e12)
    assert hist[HIST_BINS] >= 1
    assert len(hist) == HIST_BINS + 1


def test_a_bin_reports_its_geometric_midpoint():
    assert hist_bin_value(0) == QUANTILE_MIN_UA
    lower = hist_bin_value(1)
    upper = hist_bin_value(1 + HIST_PER_DECADE)
    assert upper / lower == pytest.approx(10.0)
