"""Live decimation: the port of the console's decimator, and the grid it draws.

Two kinds of test live here, and the difference matters.

The vector test replays `tests/vectors/decimation-golden.json` and compares. It
is a regression guard, not an independent check -- the vector was generated by
this same code, so on its own it only proves the implementation has not
changed. What makes it worth having is the other side: `webui/tests/decimation
.test.ts` drives the same input through the TypeScript `Decimator`, so the
vector is a contract two languages have to satisfy, and a drift in either one
shows up as a failure in the other.

Everything below it is independent: invariants and boundary values worked out
from the definitions rather than read back from the implementation.
"""

from __future__ import annotations

import json
import math
import pathlib

import pytest

from ppk2lab.capture.stats import IMPLAUSIBLE_CURRENT_UA, QUANTILE_MIN_UA
from ppk2lab_web.buckets import (
    HIST_BINS,
    HIST_PER_DECADE,
    SAMPLES_PER_BUCKET,
    Tier0Accumulator,
    hist_add,
    hist_bin_value,
    new_histogram,
)

VECTOR = pathlib.Path(__file__).parent / "vectors" / "decimation-golden.json"


def _replay(events: list[dict]) -> tuple[Tier0Accumulator, list]:
    acc = Tier0Accumulator()
    buckets = []
    for event in events:
        if event["kind"] == "gap":
            buckets.extend(acc.add_gap(event["missing"]))
        else:
            buckets.extend(
                acc.add_samples(event["ua"], bytes(event["range"]), bytes(event["logic"]))
            )
    return acc, buckets


# ---------------------------------------------------------------------------
# The cross-language vector


def test_the_golden_vector_still_describes_this_implementation():
    vector = json.loads(VECTOR.read_text())
    acc, buckets = _replay(vector["events"])

    assert len(buckets) == len(vector["buckets"])
    for got, want in zip(buckets, vector["buckets"], strict=True):
        assert got.start_index == want["start_index"]
        assert got.t0 == want["t0"]
        assert got.min_ua == want["min"]
        assert got.max_ua == want["max"]
        assert got.sum_ua == want["sum"]
        assert (got.n, got.gap, got.excluded) == (want["n"], want["gap"], want["excluded"])
        assert got.range_mask == want["rangeMask"]
        assert (got.logic_any, got.logic_all) == (want["logicAny"], want["logicAll"])
        assert got.edges == want["edges"]

    counters = vector["counters"]
    assert acc.total_stored == counters["total_stored"]
    assert acc.total_missing == counters["total_missing"]
    assert acc.total_excluded == counters["total_excluded"]
    assert acc.gap_count == counters["gap_count"]

    nonzero = {str(i): v for i, v in enumerate(acc.histogram) if v}
    assert nonzero == vector["histogram_nonzero"]


def test_the_vector_covers_more_than_one_range_and_one_decade():
    """A vector that sits in one current and one range would pass while proving
    almost nothing about either implementation."""
    vector = json.loads(VECTOR.read_text())
    masks = {b["rangeMask"] for b in vector["buckets"]}
    assert len(masks) >= 3, masks
    assert len(vector["histogram_nonzero"]) >= 3
    assert any(b["gap"] for b in vector["buckets"])
    assert any(b["edges"] for b in vector["buckets"])


# ---------------------------------------------------------------------------
# Independent invariants


def test_every_closed_bucket_accounts_for_all_hundred_samples():
    """`n + gap + excluded` is the whole bucket.

    The three bins are the three things that can be true of a sample slot: it
    arrived and is usable, it never arrived, or it arrived and cannot be
    trusted. A slot that fell out of all three would be loss the console never
    shows.
    """
    vector = json.loads(VECTOR.read_text())
    _acc, buckets = _replay(vector["events"])
    for bucket in buckets:
        assert bucket.n + bucket.gap + bucket.excluded == SAMPLES_PER_BUCKET


def test_counters_agree_with_the_buckets_they_summarise():
    vector = json.loads(VECTOR.read_text())
    acc, buckets = _replay(vector["events"])
    # The last bucket is still open, so the counters lead the closed buckets.
    assert sum(b.n for b in buckets) <= acc.total_stored
    assert sum(b.gap for b in buckets) <= acc.total_missing
    # A gap spanning three buckets is one gap, not three.
    assert acc.gap_count == 2
    assert acc.covered_fraction() == acc.total_stored / (acc.total_stored + acc.total_missing)


@pytest.mark.parametrize("seam", [1, 37, 99, 100, 101, 150, 199])
def test_an_edge_is_counted_across_a_block_seam(seam):
    """Blocks are an artefact of USB delivery, not of the signal.

    A `SampleBlock` is a gap-free run and the parser emits many per second, so
    resetting the edge state at a block boundary would drop one transition per
    block -- tens per second, each invisible on its own and all of them wrong.
    """
    logic = bytes((i // 3) % 2 * 0xFF for i in range(200))
    ua = [10.0] * 200
    ranges = bytes(200)

    whole = Tier0Accumulator()
    whole_buckets = whole.add_samples(ua, ranges, logic) + whole.flush()

    split = Tier0Accumulator()
    split_buckets = split.add_samples(ua[:seam], ranges[:seam], logic[:seam])
    split_buckets += split.add_samples(ua[seam:], ranges[seam:], logic[seam:])
    split_buckets += split.flush()

    assert sum(b.edges for b in split_buckets) == sum(b.edges for b in whole_buckets)


def test_a_gap_breaks_edge_continuity():
    """The line was not observed across the hole, so the sample after it starts
    no transition -- counting one would invent an edge nobody saw."""
    acc = Tier0Accumulator()
    acc.add_samples([1.0], bytes([0]), bytes([0x00]))
    acc.add_gap(10)
    acc.add_samples([1.0], bytes([0]), bytes([0xFF]))
    (bucket,) = acc.flush()
    assert bucket.edges == 0


def test_a_gap_spreads_across_buckets_and_counts_once():
    acc = Tier0Accumulator()
    closed = acc.add_gap(250)
    assert [b.gap for b in closed] == [100, 100]
    assert acc.gap_count == 1
    assert acc.total_missing == 250
    # The third bucket is still open with the remaining 50.
    (partial,) = acc.flush()
    assert partial.gap == 50


def test_a_gap_of_unknown_size_advances_nothing():
    """A gap the parser could not size cannot be placed on the timeline: filling
    a guess would move every later sample. The session is marked degraded
    instead, so the console can say the timeline is no longer trustworthy."""
    acc = Tier0Accumulator()
    assert acc.add_gap(None) == []
    assert acc.timeline_degraded
    assert acc.total_missing == 0
    assert acc.gap_count == 0


def test_an_empty_bucket_claims_nothing():
    """min/max are meaningless with no samples, and 0xff would claim every
    channel was high."""
    acc = Tier0Accumulator()
    (bucket,) = acc.add_gap(100)
    assert (bucket.min_ua, bucket.max_ua) == (0.0, 0.0)
    assert bucket.logic_all == 0
    assert bucket.n == 0


def test_a_flushed_bucket_leaves_the_timeline_where_it_really_ended():
    """A short bucket must not advance the index by a full width, or every
    later timestamp is wrong by the difference."""
    acc = Tier0Accumulator()
    acc.add_samples([1.0] * 30, bytes(30), bytes(30))
    (short,) = acc.flush()
    assert short.start_index == 0
    assert short.n == 30
    acc.add_samples([1.0] * 100, bytes(100), bytes(100))
    nxt = acc.flush()
    assert not nxt  # exactly one bucket closed on its own
    acc2 = Tier0Accumulator()
    acc2.add_samples([1.0] * 30, bytes(30), bytes(30))
    acc2.flush()
    closed = acc2.add_samples([1.0] * 100, bytes(100), bytes(100))
    assert closed[0].start_index == 30


