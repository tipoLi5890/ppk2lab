# Samples that arrived and cannot be used


def test_an_unusable_sample_is_neither_stored_nor_missing():
    """It was delivered, so calling it a gap accuses the instrument of loss it
    did not commit; it is not usable, so putting it in `n` poisons the mean."""
    acc = Tier0Accumulator()
    ua = [10.0, math.nan, 20.0, IMPLAUSIBLE_CURRENT_UA * 2, 30.0]
    ranges = bytes([0, 0, 0, 0, 7])  # the last one is an invalid range field
    logic = bytes(5)
    acc.add_samples(ua, ranges, logic)
    (bucket,) = acc.flush()

    assert bucket.n == 2  # 10.0 and 20.0
    assert bucket.excluded == 3
    assert bucket.gap == 0
    assert bucket.sum_ua == 30.0
    assert bucket.min_ua == 10.0
    assert bucket.max_ua == 20.0
    assert acc.total_excluded == 3
    assert acc.total_stored == 2


def test_an_unusable_sample_still_reports_its_range_and_its_logic():
    """The range field and the logic byte were real. Dropping them would hide
    framing damage and throw away digital data that is valid whether or not the
    current could be converted."""
    acc = Tier0Accumulator()
    acc.add_samples([math.nan], bytes([7]), bytes([0b1010_0000]))
    (bucket,) = acc.flush()
    assert bucket.range_mask == 1 << 7
    assert bucket.logic_any == 0b1010_0000


def test_an_unusable_sample_stays_out_of_the_distribution():
    """Bin 0 means 'at or below the 200 nA floor', which the console prints as
    an upper bound on a real current. Letting an unconvertible sample inflate
    it would turn a calibration failure into a claim about the DUT."""
    acc = Tier0Accumulator()
    acc.add_samples([math.nan, math.nan], bytes(2), bytes(2))
    assert sum(acc.histogram) == 0


